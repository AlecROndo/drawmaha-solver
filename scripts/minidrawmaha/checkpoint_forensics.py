"""What DCFR's discount did to the rung-3 table: forensics on the four 2M-iteration checkpoints.

    uv run --with modal modal volume get drawmaha-rung3 dcfr/iter-002000000.npz runs/modal/dcfr/   # and 100k, 10k
    uv run --with modal modal volume get drawmaha-rung3 cfrplus/iter-002000000.npz runs/modal/cfrplus/
    uv run --with modal modal volume get drawmaha-rung3 lcfr/iter-002000000.npz runs/modal/lcfr/
    uv run --with modal modal volume get drawmaha-rung3 vanilla/iter-002000000.npz runs/modal/vanilla/
    uv run python scripts/minidrawmaha/checkpoint_forensics.py runs/modal figures/rung3/visit_forensics.json

That is what wrote `figures/rung3/visit_forensics.json` on 2026-10-07 (from
the race's checkpoints on the Modal volume `drawmaha-rung3`; the 555 MB
files are not kept in the repo, so the JSON is committed with this script
rather than regenerated by the test suite).

**The question.** The race's DCFR tied CFR+ within 0.7% at every
checkpoint. DCFR discounts every row every iteration; under sampling a row
is touched once in thousands of iterations, so between two pieces of
evidence its negative regret is halved once per idle iteration. This
script measures how idle rows actually were, from the per-row `stamps`
(the iteration a row was last visited as the traverser) the DCFR run keeps
so its lazy discount can settle the owed factors on the next visit.

**What is recorded.**

- `never_visited_by_2M`, `visited_by_10k`, `visited_by_100k`: the share of
  the 6,220,050 rows stamped by those iterations. `1 - visited_by_10k`
  (73%) is the share of rows first reached after DCFR's positive-side
  factor k^1.5 / (k^1.5 + 1) had already reached 0.999999: for those rows
  positive regret was never discounted at all.
- `age_quantiles_iters`: quantiles of a row's age at 2M, `T - stamp`, over
  the rows ever visited; `age_ge_1075` is the share older than the 1,075
  halvings that take a float64 to exactly zero.
- `age_quantiles_reach_weighted`: the same quantiles with each row weighted
  by its share of LCFR's strategy-sum mass (how often play arrives), the
  reading that matters for exploitability; `p50` is the 7,006 the page
  quotes.
- the sign and zero fractions of each run's regret entries, DCFR's
  negatives as stored and as settled to T, and the total-variation
  distance between the four runs' current and average strategies, which
  is how close DCFR and CFR+ ended up.

The `dcfr_age.npy` beside the JSON in the paper's folder is not committed.
"""

import json
import sys
from pathlib import Path

import numpy as np

T = 2_000_000
RULES = ("dcfr", "cfrplus", "lcfr", "vanilla")


def main() -> None:
    root, out = Path(sys.argv[1]), Path(sys.argv[2])
    z = {r: np.load(root / r / f"iter-{T:09d}.npz") for r in RULES}
    widths = z["dcfr"]["widths"]
    starts = np.concatenate([[0], np.cumsum(widths)[:-1]])
    rowof = np.repeat(np.arange(widths.size), widths)
    res: dict = {}

    def rowsum(x: np.ndarray) -> np.ndarray:
        return np.add.reduceat(x, starts)

    # --- visits: stamps -----------------------------------------------------
    st2 = z["dcfr"]["stamps"]
    st1 = np.load(root / "dcfr" / "iter-000100000.npz")["stamps"]
    st10 = np.load(root / "dcfr" / "iter-000010000.npz")["stamps"]
    age = T - st2
    visited = st2 > 0
    res["rows"] = int(widths.size)
    res["never_visited_by_2M"] = float((~visited).mean())
    res["never_visited_by_100k"] = float((st1 == 0).mean())
    res["visited_by_10k"] = float((st10 > 0).mean())
    res["visited_by_100k"] = float((st1 > 0).mean())
    res["visited_by_2M"] = float(visited.mean())
    res["first_visit_after_100k_given_visited"] = float(((st1 == 0) & visited).sum() / visited.sum())
    q = np.quantile(age[visited], [0.1, 0.25, 0.5, 0.75, 0.9, 0.99])
    res["age_quantiles_iters"] = dict(zip(["p10", "p25", "p50", "p75", "p90", "p99"], q.tolist()))
    for g in (1, 10, 50, 1075):
        res[f"age_ge_{g}"] = float((age[visited] >= g).mean())

    # --- reach proxy: a row's share of LCFR's strategy-sum mass ------------
    reach = {r: rowsum(z[r]["strategy_sum"]) for r in z}
    w = reach["lcfr"] / reach["lcfr"].sum()
    res["visited_by_10k_reach_weighted"] = float(w[st10 > 0].sum())
    res["age_quantiles_reach_weighted"] = {}
    order = np.argsort(age)
    cw = np.cumsum(w[order])
    for p in (0.1, 0.5, 0.9):
        res["age_quantiles_reach_weighted"][f"p{int(p * 100)}"] = int(age[order][np.searchsorted(cw, p)])

    # --- regret signs ---------------------------------------------------------
    for r in z:
        R = z[r]["regret"]
        res[f"{r}_neg_entry_frac"] = float((R < 0).mean())
        res[f"{r}_zero_entry_frac"] = float((R == 0).mean())
    R = z["dcfr"]["regret"].copy()
    neg = R < 0
    owe = (T - st2)[rowof]  # iterations of halving still owed (the stamp's own included)
    settled = R * np.where(neg, 0.5 ** np.minimum(owe + 1, 1100), 1.0)
    res["dcfr_neg_entry_frac_settled_nonzero"] = float(
        ((settled < 0) & (np.abs(settled) > 1e-12 * np.abs(R).max())).mean()
    )

    # --- strategies: how far apart are the four runs? -------------------------
    def regret_matched(Rv: np.ndarray) -> np.ndarray:
        pos = np.maximum(Rv, 0.0)
        s = rowsum(pos)[rowof]
        n = widths[rowof]
        return np.where(s > 0, pos / np.where(s > 0, s, 1), 1.0 / n)

    def averaged(r: str) -> np.ndarray:
        ss = z[r]["strategy_sum"]
        s = rowsum(ss)[rowof]
        n = widths[rowof]
        return np.where(s > 0, ss / np.where(s > 0, s, 1), 1.0 / n)

    cur = {r: regret_matched(z[r]["regret"]) for r in z}
    av = {r: averaged(r) for r in z}
    res["tv"] = {}
    for a, b in (("dcfr", "cfrplus"), ("lcfr", "vanilla"), ("cfrplus", "vanilla"), ("dcfr", "lcfr"), ("cfrplus", "lcfr")):
        for name, S in (("current", cur), ("average", av)):
            tv = 0.5 * rowsum(np.abs(S[a] - S[b]))
            res["tv"][f"{a}~{b}|{name}"] = {
                "mean_visited": float(tv[visited].mean()),
                "reach_weighted": float((tv * w).sum()),
                "median_visited": float(np.median(tv[visited])),
            }

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(res, indent=2) + "\n")
    print(json.dumps({k: v for k, v in res.items() if k != "tv"}, indent=2))


if __name__ == "__main__":
    main()
